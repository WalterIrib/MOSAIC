#!/usr/bin/env bash
# =============================================================================
# generate_test_data.sh — build the MOSAIC functional-smoke-test dataset.
#
# SELF-CONTAINED — no external resources required. All reference files are
# included in the repo under test_data/synth_ref/:
#
#   synth_ref/genome.fa         chrSmoke (chr22:22–22.5 Mb from GRCh38; 500 kb)
#   synth_ref/annotation.gtf    GENCODE v49 subset for this region
#   synth_ref/TE.gtf            RepeatMasker TE.gtf subset
#   synth_ref/rmsk.txt.gz       UCSC rmsk table subset
#   synth_ref/dfam/             DFAM TE/satellite consensus FASTAs
#
# What this script builds (idempotent; skips completed steps):
#
#   synth_ref/star_index/       STAR genome index  (~30 s, ~15 MB)
#   synth_ref/dfam/*.bt2        bowtie2 indexes    (~5 s, ~10 MB)
#   fastq/                      synthetic PE FASTQs via wgsim (~5 s, ~3 MB)
#   coldata.tsv                 sample sheet
#   config_test.yaml            ready-to-run config pointing at synth_ref/
#
# Override via env:
#   THREADS   (default 8)
#   N_PAIRS   synthetic read pairs per sample (default 3000)
#
# Requires: STAR, wgsim, bowtie2, samtools — all in the mosaic conda env.
# Run as:  bash test_data/generate_test_data.sh
#          (with the mosaic conda env active)
# =============================================================================
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
THREADS="${THREADS:-8}"
N_PAIRS="${N_PAIRS:-3000}"

REF="$HERE/synth_ref"
FQ="$HERE/fastq"
mkdir -p "$FQ"

# ── STAR index ────────────────────────────────────────────────────────────────
echo "=== [1/4] STAR index ==="
if [[ ! -s "$REF/star_index/SAindex" ]]; then
  mkdir -p "$REF/star_index"
  GLEN=$(awk '/^[^>]/{l+=length($0)} END{print l}' "$REF/genome.fa")
  SAIDX=$(python3 -c "import math; print(min(14, int(math.log2($GLEN)/2 - 1)))")
  STAR --runMode genomeGenerate --runThreadN "$THREADS" \
       --genomeDir "$REF/star_index" \
       --genomeFastaFiles "$REF/genome.fa" \
       --sjdbGTFfile "$REF/annotation.gtf" \
       --sjdbOverhang 149 \
       --genomeSAindexNbases "$SAIDX" \
       > "$REF/star_index_build.log" 2>&1
  echo "  built (genomeSAindexNbases=$SAIDX)"
else
  echo "  already done"
fi

# ── bowtie2 indexes ───────────────────────────────────────────────────────────
echo "=== [2/4] bowtie2 DFAM indexes ==="
if [[ ! -s "$REF/dfam/consensus_TE.1.bt2" ]]; then
  bowtie2-build --quiet "$REF/dfam/consensus_TE.fa" "$REF/dfam/consensus_TE"
  echo "  consensus_TE indexed"
else
  echo "  consensus_TE already indexed"
fi
if [[ ! -s "$REF/dfam/consensus_satellite.1.bt2" ]]; then
  bowtie2-build --quiet "$REF/dfam/consensus_satellite.fa" "$REF/dfam/consensus_satellite"
  echo "  consensus_satellite indexed"
else
  echo "  consensus_satellite already indexed"
fi

# ── bwa index ─────────────────────────────────────────────────────────────────
echo "=== [2b/4] bwa index (m23) ==="
if [[ ! -s "$REF/genome.fa.bwt" ]]; then
  bwa index "$REF/genome.fa" 2>/dev/null
  echo "  built"
else
  echo "  already done"
fi

# ── synthetic FASTQs via wgsim ────────────────────────────────────────────────
echo "=== [3/4] synthetic FASTQs (wgsim, N_PAIRS=$N_PAIRS per sample) ==="
# Use deterministic but distinct seeds so samples have different counts.
declare -A SEEDS=([ChaRNA1]=101 [ChaRNA2]=202 [mito-ChaRNA1]=303 [mito-ChaRNA2]=404)
for s in ChaRNA1 ChaRNA2 mito-ChaRNA1 mito-ChaRNA2; do
  if [[ -s "$FQ/${s}_R1.fastq.gz" ]]; then
    echo "  $s: already done"
    continue
  fi
  wgsim -N "$N_PAIRS" -1 150 -2 150 \
        -e 0.005 -r 0.001 -R 0.15 \
        -S "${SEEDS[$s]}" \
        "$REF/genome.fa" \
        "$FQ/${s}_R1.fastq" "$FQ/${s}_R2.fastq" \
        > /dev/null 2>&1
  gzip -f "$FQ/${s}_R1.fastq" "$FQ/${s}_R2.fastq"
  echo "  $s: ${N_PAIRS} pairs generated"
done

# ── coldata.tsv + config_test.yaml ───────────────────────────────────────────
echo "=== [4/4] coldata + config ==="
{
  printf 'sample_id\tcondition\tfraction\tphase\tR1\tR2\n'
  for s in ChaRNA1 ChaRNA2 mito-ChaRNA1 mito-ChaRNA2; do
    case "$s" in ChaRNA*)     cond=ChaRNA;     ph=interphase ;; esac
    case "$s" in mito-ChaRNA*) cond=mito-ChaRNA; ph=mitosis    ;; esac
    printf '%s\t%s\tchromatin\t%s\t%s\t%s\n' \
      "$s" "$cond" "$ph" "$FQ/${s}_R1.fastq.gz" "$FQ/${s}_R2.fastq.gz"
  done
} > "$HERE/coldata.tsv"

cat > "$HERE/config_test.yaml" <<YAML
# Auto-generated by generate_test_data.sh — MOSAIC functional smoke test.
# Uses synthetic reads (wgsim) on a 500 kb chr22 region included in the repo.
project:
  name: mosaic_smoke
  wd: ${HERE}
  organism: human
  genome_build: hg38
  annotation_version: gencode_v49
  random_seed: 42
sequencing:
  type: PE
  read_length: 150
  strandedness: auto
library:
  prep: rRNA_depletion
  layout: PE
samples:
  fastq_dir: ${FQ}
  coldata:   ${HERE}/coldata.tsv
comparisons:
  - treatment: mito-ChaRNA
    control:   ChaRNA
databases:
  db_root:      ${REF}
  genome_fa:    ${REF}/genome.fa
  gtf:          ${REF}/annotation.gtf
  star_index:   ${REF}/star_index
  te_consensus: ${REF}/dfam/consensus_TE.fa
  te_satellite: ${REF}/dfam/consensus_satellite.fa
  rmsk_bed:     ${REF}/rmsk.txt.gz
  te_gtf:       ${REF}/TE.gtf
  auto_download: false
environments:
  main:   ${CONDA_DEFAULT_ENV:-mosaic}
  humann: humann3
  arriba: null
thresholds:
  padj: 0.05
  lfc: 0.5
  min_cov_editing: 3
  min_score_editing: 1.0
  min_ef_editing: 0.03
  editing_model: "DirMult:PHRED"
  min_reads_splicing: 3
  min_clip_te: 20
  min_support_te: 1
  min_reads_meta: 5
  min_samples_meta: 2
continue_on_error: true
modules:
  m00_download: false
  m02_trim: true
  m04_star: true
  m05_te_count: true
  m06_circrna: false
  m07_strandedness: true
  m08_deseq2: true
  m09_satellite: true
  m10_go: true
  m11_te_host: true
  m11b_promoter_te: true
  m11c_te_age: true
  m11d_te_de: true
  m12_tetranscripts: true
  m15_fusion: false
  m16_stringtie: true
  m17_rmats: true
  m18_network: true
  m19_editing: true
  m20_meta: false
  m20b_humann: false
  m23_te_insertions: true
  m14_report: true
threads: ${THREADS}
memory_gb: 12
trimming:
  min_phred: 20
  min_length: 36
  low_complexity_filter: false
  trim_poly_x: false
report:
  title: "MOSAIC smoke test"
  remove_test_notes: false
  produce_pdf: false
YAML

echo ""
echo "DONE."
echo "Run: pytest tests/ -v   or:  python tests/smoke_test.py"
